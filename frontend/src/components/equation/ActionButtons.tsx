import { useState } from "react";
import { api } from "../../api/client";
import { HelpCircle, Eye, Loader2, X } from "lucide-react";

interface ActionButtonsProps {
  equation: string;
  parameters: Record<string, number>;
}

export default function ActionButtons({ equation, parameters }: ActionButtonsProps) {
  const [mode, setMode] = useState<"what_it_does" | "why_looks_like_that" | null>(null);
  const [text, setText] = useState("");
  const [source, setSource] = useState<"ai" | "template" | null>(null);
  const [loading, setLoading] = useState(false);

  const run = async (m: "what_it_does" | "why_looks_like_that") => {
    setMode(m);
    setLoading(true);
    setText("");
    try {
      const res = await api.explain(equation, m, parameters);
      setText(res.text);
      setSource(res.source);
    } catch (e: any) {
      setText(e?.message || "Could not generate an explanation right now.");
    } finally {
      setLoading(false);
    }
  };

  return (
    <div>
      <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
        <button
          onClick={() => run("what_it_does")}
          className="flex items-center justify-center gap-2 rounded-xl border border-accent-500/40 bg-accent-500/10 hover:bg-accent-500/20 text-accent-300 font-semibold py-3.5 px-4 transition-colors"
        >
          <HelpCircle size={18} />
          WHAT DOES THIS EQUATION DO?
        </button>
        <button
          onClick={() => run("why_looks_like_that")}
          className="flex items-center justify-center gap-2 rounded-xl border border-signal-amber/40 bg-signal-amber/10 hover:bg-signal-amber/20 text-signal-amber font-semibold py-3.5 px-4 transition-colors"
        >
          <Eye size={18} />
          WHY DOES IT LOOK LIKE THAT?
        </button>
      </div>

      {mode && (
        <div className="mt-4 rounded-xl border border-base-600/60 bg-base-900/70 p-4 animate-fade-in relative">
          <button onClick={() => setMode(null)} className="absolute top-3 right-3 text-slate-500 hover:text-slate-300">
            <X size={16} />
          </button>
          <p className="text-xs font-semibold uppercase tracking-wide text-slate-500 mb-2 pr-6">
            {mode === "what_it_does" ? "What This Equation Does" : "Why It Looks Like That"}
          </p>
          {loading ? (
            <div className="flex items-center gap-2 text-slate-400 text-sm py-2">
              <Loader2 size={16} className="animate-spin" /> Thinking...
            </div>
          ) : (
            <>
              <p className="text-sm text-slate-200 leading-relaxed">{text}</p>
              {source && (
                <p className="text-[10px] text-slate-600 mt-2 uppercase tracking-wide">
                  {source === "ai" ? "Generated by AI, grounded in the analysis above" : "Generated from EquationLens's built-in explanation engine"}
                </p>
              )}
            </>
          )}
        </div>
      )}
    </div>
  );
}
